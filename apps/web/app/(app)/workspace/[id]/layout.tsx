import { WorkspaceRoute } from "@senlo/features";

export default async function WorkspaceLayout({
  children,
  params,
}: {
  children: React.ReactNode;
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;
  return <WorkspaceRoute workspaceId={Number(id)}>{children}</WorkspaceRoute>;
}
